#!/bin/bash
# Probe models of the Slingshot semantics specification (docs/spec/slingshot/): each probe runs once in
# det mode (seed and simulated time from its probe.json) and its outputs are kept as expected/.
#
#   ./probes.sh [--check] [NAME...]     default: every directory of models/probes
#
# expected/ per probe: trace.jsonl (gzip -n when > 256 KiB), tape.jsonl, measurements.csv, spd.jsonl,
# bus.jsonl, summary.json, errors.txt (exceptions thrown by event handlers, which dispose the subscriber,
# SS-BUS-7), and the projections of tools/project.py: projection.jsonl, projection-m.jsonl,
# tape-projection.jsonl (SS-X-*).
# --check runs the probes again and compares with expected/ instead of writing it.
# The models are generated by tools/probegen.py (regenerate: tools/probegen.py; then ./probes.sh).
set -uo pipefail
H="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$H/env.sh"
P="$H/models/probes"
check=0
[ "${1:-}" = --check ] && { check=1; shift; }
names=("$@")
[ ${#names[@]} -gt 0 ] || names=($(cd "$P" && ls -d */ | tr -d /))
W="$B/probes"; mkdir -p "$W"
fail=0
for n in "${names[@]}"; do
  d="$P/$n"; [ -f "$d/probe.json" ] || { echo "no probe $n" >&2; fail=1; continue; }
  T=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['sim_time'])" "$d/probe.json")
  S=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('seed', 1))" "$d/probe.json")
  o="$W/$n"; rm -rf "$o"
  timeout "${RUN_TIMEOUT:-180}" "$H/run.sh" -model "$d" -simTime "$T" -seed "$S" -out "$o" > "$W/$n.log" 2>&1
  python3 "$H/tools/project.py" "$o" > /dev/null
  # handler exceptions: "<exception>: <message> | <first Slingshot frame>", in order
  python3 - "$W/$n.log" > "$o/errors.txt" <<'EOF'
import re, sys
lines = open(sys.argv[1], errors="replace").read().splitlines()
for i, l in enumerate(lines):
    m = re.search(r"An error occurred: (\S+):: (.*)$", l)
    if not m:
        continue
    frame = next((x.strip()[3:] for x in lines[i + 1:i + 40] if "at org.palladiosimulator.analyzer.slingshot." in x), "?")
    print(f"{m.group(1)}: {m.group(2)} | {frame}")
EOF
  python3 - "$o/summary.json" <<'EOF'
import json, sys
p = sys.argv[1]
try:
    d = json.load(open(p))
except FileNotFoundError:
    sys.exit()
json.dump(d, open(p, "w"), sort_keys=True)
EOF
  files="tape.jsonl measurements.csv spd.jsonl bus.jsonl summary.json errors.txt projection.jsonl projection-m.jsonl tape-projection.jsonl"
  e="$d/expected"
  if [ $check = 1 ]; then
    r=ok
    # bus.jsonl is not compared: getDeclaredMethods() order varies between JVMs (SS-ND-1); it only
    # reorders reified subscribers of disjoint event types, which never changes a run
    for f in $files; do [ "$f" = bus.jsonl ] && continue; [ -f "$o/$f" ] || continue; cmp -s "$o/$f" "$e/$f" || r="differs: $f"; done
    if [ -f "$e/trace.jsonl.gz" ]; then zcat "$e/trace.jsonl.gz" | cmp -s - "$o/trace.jsonl" || r="differs: trace.jsonl"
    else cmp -s "$o/trace.jsonl" "$e/trace.jsonl" || r="differs: trace.jsonl"; fi
    [ "$r" = ok ] || fail=1
    echo "$n: $r"
  else
    rm -rf "$e"; mkdir -p "$e"
    for f in $files; do [ -f "$o/$f" ] && cp "$o/$f" "$e/"; done
    if [ -f "$o/trace.jsonl" ]; then
      if [ $(stat -c %s "$o/trace.jsonl") -gt 262144 ]; then gzip -n -c "$o/trace.jsonl" > "$e/trace.jsonl.gz"; else cp "$o/trace.jsonl" "$e/"; fi
    fi
    echo "$n: $(python3 -c "import json,sys; d=json.load(open(sys.argv[1])); print(d['events'], 'events,', d['rows'], 'rows')" "$o/summary.json" 2>/dev/null || echo 'no summary') , $(wc -l < "$o/errors.txt") handler errors"
  fi
done
exit $fail
