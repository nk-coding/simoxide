# Extension of lib.sh (sourced by it when CMP_EXT points here; bench/compare/SSJ.md): Palladio 5.2.2 on the SSJ
# simulation engine next to DESMO-J, plus the generated MiSArch model.
#
#   simulizar-ssj       stock SimuLizar 5.2.2, flat classpath (java/simulizar driver, engine=ssj)
#   simulizar-ssj-osgi  stock SimuLizar 5.2.2 in the product's OSGi runtime, engine by preference (cold only)
#   simucom-ssj         SimuCom 5.2.2 (simucom/ bundle), engine by preference
# and, so that both engines run from the same, current setup in one session:
#   simulizar           as in lib.sh, but the driver built by ssj/setup.sh (engine=desmoj)
#   simulizar-osgi      as in lib.sh, but a fresh OSGi configuration of ssj/setup.sh (DESMO-J by preference)
#   simucom             as in lib.sh, but the overlay install of ssj/setup.sh (DESMO-J by preference)
# Everything else falls through to lib.sh's cmd.

SSJ_HOME="$C/ssj"
SSJ_WORK="${SSJ_WORK:-$SSJ_HOME/work}"
SSJ_OVL="$SSJ_WORK/palladio-5.2.2-ssj"   # product plugins (symlinks) + the two SSJ bundles
SSJ_JARS="$SSJ_WORK/dl/org.palladiosimulator.simulation.abstractsimengine.ssj_5.2.2.jar:$SSJ_WORK/dl/ca.umontreal.iro.simul.ssj_3.3.1.jar"
SSJ_JAVA17=${SSJ_JAVA17:-$WS/jre17/bin/java}   # SimuCom: the JDT of 5.2.2 needs Java <= 17
SSJ_LAUNCHER=$(cd "$WS/palladio-5.2.2/plugins" 2>/dev/null && ls org.eclipse.equinox.launcher_*.jar | head -1)
# engine ids of the extension point de.uka.ipd.sdq.simulation.abstractsimengine.engine (plugin.xml of each bundle)
SSJ_ENGINE_ID_desmoj=de.uka.ipd.sdq.simucomframework.desmoj.engine1
SSJ_ENGINE_ID_ssj=org.palladiosimulator.simulation.abstractsimengine.ssj

# reference/build/classpath.txt keeps the absolute paths of the install it was generated from; if that install has
# moved (palladio-research -> old/palladio-research), map its prefix to $PR.
_ssj_first=${SL_CP%%:*}
if [ -n "$_ssj_first" ] && [ ! -e "$_ssj_first" ] && [[ $_ssj_first == */work-simucom/* ]]; then
  SL_CP=${SL_CP//${_ssj_first%%/work-simucom/*}\/work-simucom\//$PR/work-simucom/}
  REFSIM_CP="$B/refsim:$R/reference/build/classes-patches:$R/reference/build/classes-base:$SL_CP"
fi
unset _ssj_first

# MiSArch (generated by msa-sim, ssj/models/x_misarch/SOURCE.txt): 361 s is msa-sim's own run length
SIMTIME[x_misarch]="36 361"

declare -f _cmp_lib_model_dir > /dev/null || eval "_cmp_lib_$(declare -f model_dir)"   # once
model_dir() { # sim model
  case "$1:$2" in
    simucom*:x_misarch) echo "$SSJ_WORK/models/x_misarch_simucom" ;;   # Java-safe entity names (sanitize-names.py)
    *:x_misarch) echo "$SSJ_HOME/models/x_misarch" ;;
    *) _cmp_lib_model_dir "$@" ;;
  esac
}

declare -f _cmp_lib_supported > /dev/null || eval "_cmp_lib_$(declare -f supported)"
supported() { # sim model
  case "$1:$2" in
    # SimuCom's code generation cannot handle the generated MiSArch model, not even with Java-safe names
    # (sanitize-names.py): "product.impl cannot be resolved to a type" (SSJ.md)
    simucom*:x_misarch) return 1 ;;
    *) _cmp_lib_supported "$@" ;;
  esac
}

declare -f _cmp_lib_cmd > /dev/null || eval "_cmp_lib_$(declare -f cmd)"
cmd() {
  local sim=$1 model=$2 len=$3 w=$4 n=$5; shift 5
  local dir; dir=$(model_dir "$sim" "$model")
  local T; T=$(simtime "$model" "$len")
  local common="model=$dir simTime=$T maxMeas=-1 seed=$SEED warmup=$w runs=$n"
  local jo=${JO:-$JOPTS}
  case "$sim" in
    simulizar)     echo "$JAVA $jo -cp $SSJ_WORK/build/simulizar:$SL_CP cmpsl.CompareSimuLizar $PLUGINS $common engine=desmoj $*" ;;
    simulizar-ssj) echo "$JAVA $jo -cp $SSJ_WORK/build/simulizar:$SL_CP:$SSJ_JARS cmpsl.CompareSimuLizar $PLUGINS $common engine=ssj sim=simulizar-ssj $*" ;;
    simucom|simucom-ssj)
      local e=desmoj; [ "$sim" = simucom-ssj ] && e=ssj
      echo "env JVM_OPTS='$jo' JAVA=$SSJ_JAVA17 PALLADIO=$SSJ_OVL SIMUCOM_WORK=$SSJ_WORK/simucom-$e $C/simucom/run-simucom.sh $dir $T $n $SEED warmup=$w sim=$sim $*" ;;
    simulizar-osgi|simulizar-ssj-osgi)
      local e=desmoj; [ "$sim" = simulizar-ssj-osgi ] && e=ssj
      echo "env JVM_OPTS='$jo' JAVA=$JAVA $SSJ_HOME/run-simulizar-osgi.sh $e models=$dir runs=1 threads=1 maxMeasurements=-1 simTime=$T quiet=true" ;;
    *) _cmp_lib_cmd "$sim" "$model" "$len" "$w" "$n" "$@" ;;
  esac
}
