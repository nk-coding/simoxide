package headless.simucom;

import java.io.IOException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Enumeration;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import org.eclipse.core.resources.IProject;
import org.eclipse.core.runtime.IProgressMonitor;
import org.eclipse.core.runtime.Platform;
import org.osgi.framework.Bundle;
import org.palladiosimulator.analyzer.workflow.jobs.CreatePluginProjectJob;

import de.uka.ipd.sdq.workflow.jobs.CleanupFailedException;
import de.uka.ipd.sdq.workflow.jobs.IJob;
import de.uka.ipd.sdq.workflow.jobs.JobFailedException;
import de.uka.ipd.sdq.workflow.jobs.UserCanceledException;

/**
 * Repairs the code generated by the (outdated) SimuCom Xtend templates of Palladio 5.2.2: the templates still
 * reference framework classes under de.uka.ipd.sdq.simucomframework.{model,resources,probes,...}, which moved to
 * de.uka.ipd.sdq.simucomframework.core.* (bundle de.uka.ipd.sdq.simucomframework.core, re-exported by
 * de.uka.ipd.sdq.simucomframework). Runs after code generation and before the JDT/PDE compile.
 */
public class FixGeneratedSourcesJob implements IJob {

    private static final String OLD = "de.uka.ipd.sdq.simucomframework.";
    private static final String NEW = "de.uka.ipd.sdq.simucomframework.core.";
    private static Map<Pattern, String> RENAMES;
    static int filesChanged, replacements;

    private final String storagePluginId;

    public FixGeneratedSourcesJob(String storagePluginId) {
        this.storagePluginId = storagePluginId;
    }

    /** old FQN -> new FQN for every top-level class of simucomframework.core that does not exist at its old place. */
    static synchronized Map<Pattern, String> renames() {
        if (RENAMES != null) return RENAMES;
        Set<String> core = classes("de.uka.ipd.sdq.simucomframework.core", "/de/uka/ipd/sdq/simucomframework/core");
        Set<String> old = classes("de.uka.ipd.sdq.simucomframework", "/de/uka/ipd/sdq/simucomframework");
        Map<Pattern, String> m = new LinkedHashMap<>();
        for (String c : core) {
            String rel = c.substring(NEW.length()); // e.g. model.SimuComModel or SimuComConfig
            String oldFqn = OLD + rel;
            if (old.contains(oldFqn)) continue;
            m.put(Pattern.compile("(?<![A-Za-z0-9_.])" + Pattern.quote(oldFqn) + "(?![A-Za-z0-9_])"), c);
        }
        RENAMES = m;
        return m;
    }

    private static Set<String> classes(String bsn, String root) {
        Set<String> r = new HashSet<>();
        Bundle b = Platform.getBundle(bsn);
        Enumeration<URL> e = b.findEntries(root, "*.class", true);
        while (e != null && e.hasMoreElements()) {
            String p = e.nextElement().getPath();
            if (p.contains("$")) continue;
            if (p.startsWith("/")) p = p.substring(1);
            r.add(p.substring(0, p.length() - ".class".length()).replace('/', '.'));
        }
        return r;
    }

    @Override
    public void execute(IProgressMonitor monitor) throws JobFailedException, UserCanceledException {
        IProject project = CreatePluginProjectJob.getProject(storagePluginId);
        Path root = project.getLocation().toFile().toPath();
        Path src = root.resolve("src");
        Map<Pattern, String> ren = renames();
        try (Stream<Path> s = Files.walk(src)) {
            List<Path> files = s.filter(p -> p.toString().endsWith(".java")).collect(Collectors.toList());
            for (Path f : files) {
                String text = Files.readString(f, StandardCharsets.UTF_8);
                String orig = text;
                if (text.contains(OLD)) {
                    for (Map.Entry<Pattern, String> e : ren.entrySet()) {
                        Matcher mt = e.getKey().matcher(text);
                        StringBuilder sb = new StringBuilder();
                        int n = 0;
                        while (mt.find()) {
                            mt.appendReplacement(sb, Matcher.quoteReplacement(e.getValue()));
                            n++;
                        }
                        if (n > 0) {
                            mt.appendTail(sb);
                            text = sb.toString();
                            replacements += n;
                        }
                    }
                }
                text = SourcePatches.apply(f, text);
                if (!text.equals(orig)) {
                    Files.writeString(f, text, StandardCharsets.UTF_8);
                    filesChanged++;
                }
            }
        } catch (IOException e) {
            throw new JobFailedException("Fixing generated SimuCom sources failed", e);
        }
        try {
            project.refreshLocal(org.eclipse.core.resources.IResource.DEPTH_INFINITE, monitor);
        } catch (org.eclipse.core.runtime.CoreException e) {
            throw new JobFailedException("Refreshing generated project failed", e);
        }
    }

    @Override
    public void cleanup(IProgressMonitor monitor) throws CleanupFailedException {
    }

    @Override
    public String getName() {
        return "Fix generated SimuCom sources for 5.2.2 package layout";
    }
}
