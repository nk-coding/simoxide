//! Generates `src/messages_data.rs`: the message texts of Eclipse's analyser, read from the
//! `.properties` files of the reference checkouts with `java.util.Properties` semantics.
//!
//! ```sh
//! cargo run -p qvto-sema --example gen_messages            # writes src/messages_data.rs
//! cargo run -p qvto-sema --example gen_messages -- --check # fails if out of date
//! ```
//!
//! `QVTO_ECLIPSE_DIR` / `QVTO_OCL_DIR` override the checkout locations.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const BUNDLES: &[(&str, &str, &str)] = &[
    (
        "validation",
        "qvto",
        "plugins/org.eclipse.m2m.qvt.oml/src/org/eclipse/m2m/internal/qvt/oml/ast/parser/ValidationMessages.properties",
    ),
    (
        "compiler",
        "qvto",
        "plugins/org.eclipse.m2m.qvt.oml/src/org/eclipse/m2m/internal/qvt/oml/compiler/CompilerMessages.properties",
    ),
    (
        "ocl",
        "ocl",
        "plugins/org.eclipse.ocl/src/org/eclipse/ocl/internal/l10n/OCLMessages.properties",
    ),
];

/// `java.util.Properties.load` for the subset the files use: comments (`#`, `!`), `key=value`,
/// `key:value`, `key value`, line continuations, `\uXXXX` and the usual escapes.
fn parse_properties(text: &str) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = Vec::new();
    // join logical lines
    let mut logical = Vec::new();
    let mut cur = String::new();
    let mut continuing = false;
    for raw in text.split('\n') {
        let raw = raw.strip_suffix('\r').unwrap_or(raw);
        let line = if continuing {
            raw.trim_start_matches([' ', '\t', '\x0c'])
        } else {
            let t = raw.trim_start_matches([' ', '\t', '\x0c']);
            if t.is_empty() || t.starts_with('#') || t.starts_with('!') {
                continue;
            }
            t
        };
        // count trailing backslashes
        let n = line.chars().rev().take_while(|&c| c == '\\').count();
        if n % 2 == 1 {
            cur.push_str(&line[..line.len() - 1]);
            continuing = true;
        } else {
            cur.push_str(line);
            logical.push(std::mem::take(&mut cur));
            continuing = false;
        }
    }
    if !cur.is_empty() {
        logical.push(cur);
    }
    for l in logical {
        let chars: Vec<char> = l.chars().collect();
        let mut i = 0;
        let mut key_end = chars.len();
        while i < chars.len() {
            let c = chars[i];
            if c == '\\' {
                i += 2;
                continue;
            }
            if c == '=' || c == ':' || c == ' ' || c == '\t' || c == '\x0c' {
                key_end = i;
                break;
            }
            i += 1;
        }
        let key_raw: String = chars[..key_end.min(chars.len())].iter().collect();
        let mut j = key_end;
        while j < chars.len() && matches!(chars[j], ' ' | '\t' | '\x0c') {
            j += 1;
        }
        if j < chars.len() && (chars[j] == '=' || chars[j] == ':') {
            j += 1;
        }
        while j < chars.len() && matches!(chars[j], ' ' | '\t' | '\x0c') {
            j += 1;
        }
        let value_raw: String = chars[j.min(chars.len())..].iter().collect();
        let key = unescape(&key_raw);
        let value = unescape(&value_raw);
        if let Some(e) = out.iter_mut().find(|(k, _)| *k == key) {
            e.1 = value;
        } else {
            out.push((key, value));
        }
    }
    out
}

fn unescape(s: &str) -> String {
    let mut out = String::new();
    let mut it = s.chars().peekable();
    while let Some(c) = it.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match it.next() {
            Some('t') => out.push('\t'),
            Some('n') => out.push('\n'),
            Some('r') => out.push('\r'),
            Some('f') => out.push('\x0c'),
            Some('u') => {
                let hex: String = (0..4).filter_map(|_| it.next()).collect();
                let v = u32::from_str_radix(&hex, 16).expect("\\u escape");
                out.push(char::from_u32(v).unwrap_or('\u{fffd}'));
            }
            Some(o) => out.push(o),
            None => {}
        }
    }
    out
}

fn root(var: &str, default: &str) -> PathBuf {
    std::env::var(var)
        .map(PathBuf::from)
        .unwrap_or_else(|_| Path::new(env!("CARGO_MANIFEST_DIR")).join(default))
}

fn main() {
    let qvto = root("QVTO_ECLIPSE_DIR", "../../reference/eclipse-qvto");
    let ocl = root("QVTO_OCL_DIR", "../../reference/eclipse-ocl");
    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p qvto-sema --example gen_messages` from Eclipse QVTo's\n\
         // ValidationMessages.properties and CompilerMessages.properties and classic OCL's\n\
         // OCLMessages.properties (EPL-2.0). Do not edit.\n\n",
    );
    for (module, which, rel) in BUNDLES {
        let base = if *which == "qvto" { &qvto } else { &ocl };
        let path = base.join(rel);
        let text =
            std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let props = parse_properties(&text);
        writeln!(out, "/// `{}`", rel.rsplit('/').next().unwrap()).unwrap();
        writeln!(out, "#[allow(non_upper_case_globals, dead_code)]").unwrap();
        writeln!(out, "pub mod {module} {{").unwrap();
        for (k, v) in &props {
            let ident: String = k
                .chars()
                .map(|c| {
                    if c.is_ascii_alphanumeric() || c == '_' {
                        c
                    } else {
                        '_'
                    }
                })
                .collect();
            writeln!(out, "    pub const {ident}: &str = {v:?};").unwrap();
        }
        writeln!(out, "}}\n").unwrap();
    }
    let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/messages_data.rs");
    if std::env::args().any(|a| a == "--check") {
        if std::fs::read_to_string(&target).unwrap_or_default() != out {
            eprintln!("src/messages_data.rs is out of date");
            std::process::exit(1);
        }
        return;
    }
    std::fs::write(&target, out).unwrap();
    eprintln!("wrote {}", target.display());
}
