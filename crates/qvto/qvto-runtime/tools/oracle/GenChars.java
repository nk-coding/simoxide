// Generates src/java/chars_data.rs: the Character data of the running JDK that Java string
// operations use (see src/java/chars.rs). Run through gen-chars.sh.
import java.util.*;

public class GenChars {
    static StringBuilder out = new StringBuilder();

    interface CharPred { boolean test(int c); }
    interface CpMap { int map(int cp); }

    static void ranges(String name, int max, CharPred p) {
        out.append("pub static ").append(name).append(": &[(u32, u32)] = &[");
        int n = 0;
        for (int c = 0; c <= max; ) {
            if (!p.test(c)) { c++; continue; }
            int s = c;
            while (c + 1 <= max && p.test(c + 1)) c++;
            if (n++ % 6 == 0) out.append("\n    ");
            out.append(String.format("(0x%x, 0x%x), ", s, c));
            c++;
        }
        out.append("\n];\n\n");
    }

    /** Sorted (code point, mapped code point) pairs where the mapping is not the identity. */
    static void pairs(String name, int max, CpMap m) {
        out.append("pub static ").append(name).append(": &[(u32, u32)] = &[");
        int n = 0;
        for (int c = 0; c <= max; c++) {
            int v = m.map(c);
            if (v == c) continue;
            if (n++ % 6 == 0) out.append("\n    ");
            out.append(String.format("(0x%x, 0x%x), ", c, v));
        }
        out.append("\n];\n\n");
    }

    static String units(String s) {
        StringBuilder b = new StringBuilder("&[");
        for (int i = 0; i < s.length(); i++) b.append(String.format("0x%x, ", (int) s.charAt(i)));
        return b.append("]").toString();
    }

    public static void main(String[] a) {
        out.append("// Generated by tools/oracle/GenChars.java from ").append(System.getProperty("java.vendor"))
           .append(" ").append(System.getProperty("java.version")).append(". Do not edit.\n\n");
        ranges("WHITESPACE", 0xffff, c -> Character.isWhitespace((char) c));
        ranges("LETTER", 0xffff, c -> Character.isLetter((char) c));
        ranges("LETTER_OR_DIGIT", 0xffff, c -> Character.isLetterOrDigit((char) c));
        ranges("CASED", 0x10ffff, c -> Character.isLowerCase(c) || Character.isUpperCase(c) || Character.isTitleCase(c));
        ranges("CASE_IGNORABLE", 0x10ffff, c -> {
            int t = Character.getType(c);
            return t == Character.NON_SPACING_MARK || t == Character.ENCLOSING_MARK || t == Character.FORMAT
                || t == Character.MODIFIER_LETTER || t == Character.MODIFIER_SYMBOL
                || c == '\'' || c == 0x2019 || c == '.' || c == ':' || c == 0xb7 || c == 0x387 || c == 0x5f4 || c == 0x2018 || c == 0x2024 || c == 0xfe13 || c == 0xfe52 || c == 0xfe55 || c == 0xff07 || c == 0xff0e || c == 0xff1a;
        });
        // decimal digit runs: (start, end) with Character.digit(start + k, 10) == k
        out.append("pub static DIGITS: &[(u32, u32)] = &[");
        int n = 0;
        for (int c = 0; c <= 0xffff; c++) {
            if (Character.digit((char) c, 10) == 0) {
                int e = c;
                while (e + 1 <= 0xffff && Character.digit((char) (e + 1), 10) == e + 1 - c) e++;
                if (n++ % 6 == 0) out.append("\n    ");
                out.append(String.format("(0x%x, 0x%x), ", c, e));
                c = e;
            } else if (Character.digit((char) c, 10) > 0 && Character.digit((char) (c - 1), 10) != Character.digit((char) c, 10) - 1) {
                throw new IllegalStateException("digit run not starting at 0: " + c);
            }
        }
        out.append("\n];\n\n");
        pairs("UPPER", 0x10ffff, Character::toUpperCase);
        pairs("LOWER", 0x10ffff, Character::toLowerCase);
        // full (string) case mappings that differ from the simple ones
        out.append("pub static UPPER_SPECIAL: &[(u32, &[u16])] = &[\n");
        for (int c = 0; c <= 0x10ffff; c++) {
            if (c >= 0xd800 && c <= 0xdfff) continue;
            String s = new String(Character.toChars(c));
            String u = s.toUpperCase(Locale.ROOT);
            if (!u.equals(new String(Character.toChars(Character.toUpperCase(c)))))
                out.append(String.format("    (0x%x, %s),\n", c, units(u)));
        }
        out.append("];\n\n");
        out.append("pub static LOWER_SPECIAL: &[(u32, &[u16])] = &[\n");
        for (int c = 0; c <= 0x10ffff; c++) {
            if (c >= 0xd800 && c <= 0xdfff) continue;
            String s = new String(Character.toChars(c));
            String l = s.toLowerCase(Locale.ROOT);
            if (!l.equals(new String(Character.toChars(Character.toLowerCase(c)))))
                out.append(String.format("    (0x%x, %s),\n", c, units(l)));
        }
        out.append("];\n");
        System.out.print(out);
    }
}
