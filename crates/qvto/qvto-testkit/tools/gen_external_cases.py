#!/usr/bin/env python3
"""Generates cases/external.cases: one compile-only case per new .qvto file of the external
corpus (reference/external/FILES.tsv, status "new"), for the comparison of compile problems
with Eclipse (`qvto fuzz corpus`). Run from the repository root:
  python3 -I crates/qvto-testkit/tools/gen_external_cases.py [--all]
Per case:
- the metamodel files FILES.tsv lists for its model types (`mmfile`), PCM through the PCM
  configuration (`conf target/pcm/pcm.conf`);
- `urimap`s for platform:/plugin and platform:/resource URIs that those metamodels reference,
  to a directory of that bundle/project name in the same source (else in _metamodels);
- the import root: the nearest ancestor folder under which the most `import`ed units exist
  (`a.b.C` as `a/b/C.qvto`), else the file's folder.
Without --all, files whose metamodels are partly missing are left out.
"""
import csv, os, re, sys

EXT = 'reference/external'
ALL = '--all' in sys.argv
# --run: run cases (transformations without blackboxes whose in/inout parameters all have a
# candidate input model of the parameter's metamodel) into cases/external-run.cases
RUN = '--run' in sys.argv
rows = [r for r in csv.DictReader(open(os.path.join(EXT, 'FILES.tsv'), encoding='utf-8'), delimiter='\t')
        if r['status'] == 'new']

# directories by base name, per source and in _metamodels, for platform: URI maps
dirs_by_name = {}
for top in sorted(os.listdir(EXT)):
    p = os.path.join(EXT, top)
    if not os.path.isdir(p) or top == '_work':
        continue
    for d, subdirs, files in os.walk(p):
        subdirs[:] = [s for s in subdirs if s != '.git']
        dirs_by_name.setdefault(os.path.basename(d), []).append(d)

# platform: URIs the PCM configuration maps (a case's own map of the same key would replace it
# and, removed after the case, leave the Java runner's JVM without it)
CONF_MAPS = set()
try:
    for line in open('target/pcm/pcm.conf', encoding='utf-8'):
        f = line.split()
        if len(f) >= 3 and f[0] == 'map':
            CONF_MAPS.add(f[1])
except OSError:
    pass

PLATFORM = re.compile(r'platform:/(plugin|resource)/([^/"#\s]+)/')
IMPORT = re.compile(r'^\s*(?:import|access|extends)\s+(?:library\s+|transformation\s+)?([A-Za-z_][\w.]*)\s*[;(]', re.M)

def bundle_dir(name, source):
    cands = dirs_by_name.get(name, [])
    same = [c for c in cands if c.startswith(os.path.join(EXT, source) + '/')]
    meta = [c for c in cands if c.startswith(os.path.join(EXT, '_metamodels') + '/')]
    for group in (same, meta, cands):
        if group:
            return sorted(group, key=len)[0]
    return None

def import_root(path, source):
    folder = os.path.dirname(path)
    try:
        text = open(path, encoding='utf-8', errors='replace').read()
    except OSError:
        return folder
    names = [n for n in IMPORT.findall(text) if '.' in n or True]
    if not names:
        return folder
    best, best_n = folder, -1
    d = folder
    stop = os.path.join(EXT, source)
    while True:
        n = sum(1 for q in names if os.path.isfile(os.path.join(d, q.replace('.', '/') + '.qvto')))
        if n > best_n:
            best, best_n = d, n
        if d == stop or len(d) <= len(stop):
            break
        d = os.path.dirname(d)
    return best

MODELTYPE = re.compile(r"modeltype\s+(\w+)\s+uses\s+(?:[\w.]+\s*)?\(?\s*['\"]([^'\"]+)['\"]", re.S)
HEADER = re.compile(r"transformation\s+[\w.]+\s*\(([^)]*)\)", re.S)
ROOT_NS = re.compile(r"<(?:(\w+):)?[\w.]+[^>]*?>", re.S)

def root_namespaces(path):
    """The namespace URIs a model file declares on its root element."""
    try:
        head = open(path, encoding='utf-8', errors='replace').read(8192)
    except OSError:
        return set()
    m = re.search(r"<(?!\?|!)[^>]*>", head, re.S)
    if not m:
        return set()
    return set(re.findall(r'xmlns(?::\w+)?="([^"]+)"', m.group(0)))

def run_inputs(path, r):
    """In/inout parameter models (paths) in signature order, or None."""
    try:
        text = open(path, encoding='utf-8', errors='replace').read()
    except OSError:
        return None
    mts = {n: u for n, u in MODELTYPE.findall(text)}
    h = HEADER.search(text)
    if not h:
        return None
    cands = [c for c in r['input_models'].split(',') if c and c != 'none']
    out = []
    for part in [x.strip() for x in h.group(1).split(',') if x.strip()]:
        m = re.match(r"(in|out|inout)?\s*(\w+)?\s*:?\s*(\w+)$", part)
        if not m:
            return None
        direction = m.group(1) or 'in'
        mt = m.group(3)
        if direction == 'out':
            continue
        uri = mts.get(mt)
        pick = next((c for c in cands if uri and uri in root_namespaces(os.path.join(EXT, c))), None)
        if pick is None:
            return None
        out.append(os.path.join(EXT, pick))
    return out

out = ['# Generated by crates/qvto-testkit/tools/gen_external_cases.py from reference/external/FILES.tsv:',
       '# one compile-only case per new .qvto file of the external corpus (PLAN Q7), compared with',
       "# Eclipse's compile problems by `qvto fuzz corpus` (needs reference/external, not committed).", '']
n = 0
skipped = 0
for r in rows:
    path = os.path.join(EXT, r['path'])
    if not os.path.isfile(path):
        continue
    mms = [m for m in r['metamodel_files'].split(',') if m]
    if not ALL and any(m.startswith('missing') for m in mms):
        skipped += 1
        continue
    inputs = None
    if RUN:
        if r['kind'] != 'transformation' or r['blackboxes'] not in ('-', ''):
            continue
        inputs = run_inputs(path, r)
        if inputs is None:
            continue
    folder = os.path.dirname(path)
    cid = 'ext__' + re.sub(r'[^A-Za-z0-9_.-]', '_', r['path'][:-5].replace('/', '__'))
    lines = [f'case {cid}', 'driver external', 'kind run' if RUN else 'kind compile', 'features external',
             f'dir {folder}', f'qvto {os.path.basename(path)}']
    for i in inputs or []:
        lines.append(f'in {os.path.relpath(i, folder)}')
    maps = {}
    pcm = False
    for m in mms:
        if m == 'pcm':
            pcm = True
            continue
        if m.startswith('builtin') or m.startswith('missing'):
            continue
        mp = os.path.join(EXT, m)
        if not os.path.isfile(mp):
            continue
        lines.append(f'mmfile {os.path.relpath(mp, folder)}')
        try:
            text = open(mp, encoding='utf-8', errors='replace').read()
        except OSError:
            continue
        for kind, name in PLATFORM.findall(text):
            key = f'platform:/{kind}/{name}/'
            if name == 'org.eclipse.emf.ecore' or key in CONF_MAPS:
                continue  # Ecore itself (an alias), or mapped by the configuration
            if key not in maps:
                b = bundle_dir(name, r['source'])
                if b:
                    maps[key] = b
    # always: the Java runner's configurations are JVM-wide once applied (Env.applyConf), so
    # every case sees the Palladio metamodels in the global registry on both sides
    lines.append('conf target/pcm/pcm.conf')
    for k, v in sorted(maps.items()):
        lines.append(f'urimap {k} {v}')
    lines.append(f'imports root {import_root(path, r["source"])}')
    lines.append(f'note source {r["source"]}')
    if not RUN:
        lines.append('check problems 0 -1')
    lines.append('end')
    out.append('\n'.join(lines) + '\n')
    n += 1
target = 'crates/qvto-testkit/cases/external-run.cases' if RUN else 'crates/qvto-testkit/cases/external.cases'
open(target, 'w', encoding='utf-8').write('\n'.join(out))
print(f'{n} cases ({skipped} left out: metamodels missing)')
