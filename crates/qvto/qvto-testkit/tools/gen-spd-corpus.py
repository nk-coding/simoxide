def xmlns(*prefixes):
    return " ".join(f'xmlns:{p}="{NS[p]}"' for p in prefixes)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if text.startswith("<?xml") and HEADER not in text:
        decl, rest = text.split("\n", 1)
        text = decl + "\n" + HEADER + "\n" + rest
    with open(path, "w") as f:
        f.write(text)


def with_header(text):
    """Adds the header to a copied XMI file (after the XML declaration)."""
    if HEADER in text:
        return text
    decl, rest = text.split("\n", 1)
    return decl + "\n" + HEADER + "\n" + rest


# ------------------------------------------------------------------------------- SPD models

def trigger(tid, t):
    return (f'    <scalingTrigger xsi:type="triggers:SimpleFireOnValue" id="{tid}" relationalOperator="EqualTo">\n'
            f'      <stimulus xsi:type="stimuli:SimulationTime"/>\n'
            f'      <expectedValue xsi:type="expectations:ExpectedTime" value="{t}"/>\n'
            f'    </scalingTrigger>\n')


def adjustment(kind, value, min_adj=None):
    if kind == "step":
        return f'    <adjustmentType xsi:type="adjustments:StepAdjustment" stepValue="{value}"/>\n'
    if kind == "rel":
        m = f' minAdjustmentValue="{min_adj}"' if min_adj is not None else ""
        return f'    <adjustmentType xsi:type="adjustments:RelativeAdjustment" percentageGrowthValue="{value}"{m}/>\n'
    if kind == "abs":
        return f'    <adjustmentType xsi:type="adjustments:AbsoluteAdjustment" goalValue="{value}"/>\n'
    raise ValueError(kind)


def spd_model(spd_id, policies, groups):
    """policies: (id, name, group id, (kind, value[, min])); groups: (xsi type, id, name, ref feature,
    href, [(min, max)])."""
    out = [f'<?xml version="1.0" encoding="UTF-8"?>\n<spd:SPD {XMI} '
           f'{xmlns("adjustments", "expectations", "spd", "stimuli", "target", "targets", "triggers")} '
           f'id="{spd_id}" entityName="Q1 policies">\n']
    for i, (pid, name, group, adj) in enumerate(policies):
        out.append(f'  <scalingPolicies id="{pid}" entityName="{name}" active="true" targetGroup="{group}">\n')
        out.append(adjustment(*adj))
        out.append(trigger(pid + "T", 10.0 * (i + 1)))
        out.append("  </scalingPolicies>\n")
    for xsi, gid, name, feat, href, constraints in groups:
        out.append(f'  <targetGroups xsi:type="targets:{xsi}" id="{gid}" entityName="{name}">\n')
        for j, (lo, hi) in enumerate(constraints):
            out.append(f'    <targetConstraints xsi:type="target:TargetGroupSizeConstraint" id="{gid}C{j}" '
                       f'minSize="{lo}" maxSize="{hi}"/>\n')
        out.append(f'    <{feat} href="{href}"/>\n')
        out.append("  </targetGroups>\n")
    out.append("</spd:SPD>\n")
    return "".join(out)


