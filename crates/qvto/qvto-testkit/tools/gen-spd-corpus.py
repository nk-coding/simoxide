def min_semantic(policy, variant=None):
    """The example's configuration with the enacted policy; variants break it."""
    with open(os.path.join(MIN_SRC, "default.semanticspd")) as f:
        text = f.read()
    text = re.sub(r'\s*<enactedPolicy href="[^"]*"/>', "", text)
    if policy:
        text = text.replace(f'<spd href="default.spd#{MIN_SPD}"/>',
                            f'<spd href="default.spd#{MIN_SPD}"/>\n  <enactedPolicy href="default.spd#{policy}"/>')
    if variant == "no-repository":
        text = re.sub(r'\s*<repository href="[^"]*"/>', "", text)
    if variant == "no-ei-cfg":
        text = re.sub(r'\s*<targetCfgs xsi:type="semanticspd:ElasticInfrastructureCfg">.*?</targetCfgs>', "", text,
                      flags=re.S)
    return text


