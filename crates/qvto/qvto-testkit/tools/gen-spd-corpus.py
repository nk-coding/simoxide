def main():
    shutil.rmtree(Q1, ignore_errors=True)
    gen_min()
    gen_full()
    done_states = {"min", "full"}
    pending = list(CASES_DEF)
    blocks = {}
    level = 0
    while pending:
        level += 1
        ready = [c for c in pending if c[1] in done_states]
        if not ready:
            sys.exit("unresolvable states: " + ", ".join(sorted({c[1] for c in pending})))
        for cid, state, cfg, note in ready:
            write_cfg(cid, state, cfg)
            blocks[cid] = case_block(cid, state, cfg_path(cid, state, cfg), note)
        pending = [c for c in pending if c not in ready]
        # the states the remaining cases need, from the cases just written
        need = {c[1] for c in pending if c[1] not in done_states}
        srcs = sorted({s.removesuffix("-noid") for s in need} & set(blocks))
        if srcs:
            tmp = os.path.join(SCRATCH, f"level{level}.cases")
            os.makedirs(SCRATCH, exist_ok=True)
            with open(tmp, "w") as f:
                f.write("\n".join(blocks[s] for s in srcs))
            run_java(tmp, os.path.join(SCRATCH, "java"))
            for s in need:
                src = s.removesuffix("-noid")
                if src in srcs:
                    make_state(src, s, assign_ids=not s.endswith("-noid"))
                    done_states.add(s)
    with open(CASES, "w") as f:
        f.write("# SPD adjustment corpus (DESIGN-SPD Q1): Slingshot's MainTransformation on every path.\n"
                "# Generated by qvto-testkit/tools/gen-spd-corpus.py (models in corpus/spd/q1, derived from\n"
                f"# {SOURCES};\n"
                "# licence pending confirmation, DESIGN-SPD U3). The transformations bind the models by\n"
                "# nsURI in Slingshot; here positionally, in the signature's order.\n\n")
        f.write("\n".join(blocks[c[0]] for c in CASES_DEF))
    print(f"{len(CASES_DEF)} cases in {CASES}; states: {', '.join(sorted(done_states))}")


if __name__ == "__main__":
    main()
